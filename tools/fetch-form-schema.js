/**
 * Reads the source Google Form and rewrites lib/form-schema.js so the cloned
 * web page matches it exactly — questions, order, required flags and choices.
 *
 *   node tools/fetch-form-schema.js [viewform-url]
 *
 * Requires the form to be shared as "Anyone with the link". A restricted form
 * returns a sign-in page and this prints a manual fallback instead.
 */
import { writeFileSync } from 'node:fs';
import { FORM } from '../lib/form-schema.js';

// Google's item type codes.
const TYPE = { 0: 'short', 1: 'paragraph', 2: 'choice', 3: 'choice', 4: 'checkbox', 5: 'scale', 9: 'date', 10: 'time' };

const slug = (s, id) =>
  (String(s).toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '') || `field_${id}`).slice(0, 40);

// String.raw so the regex backslashes survive into the printed snippet.
const CONSOLE_SNIPPET = String.raw`copy([...document.querySelectorAll('[data-params]')].map(e=>{
  const p=e.getAttribute('data-params');
  const t=(p.match(/"([^"]+)",\d+,\[\[(\d+)/)||[])[1];
  const i=(p.match(/,\[\[(\d+)/)||[])[1];
  return i?{label:t,entry:'entry.'+i}:null;
}).filter(Boolean).map(o=>JSON.stringify(o)).join(',\n'));`;

function buildSchemaFile({ responseUrl, title, description, emailField, nameField, fields }) {
  return `/**
 * The cloned Google Form definition.
 * GENERATED by tools/fetch-form-schema.js on ${new Date().toISOString()}
 * Re-run that script if the source form changes.
 */

export const FORM = {
  responseUrl: ${JSON.stringify(responseUrl)},

  title: ${JSON.stringify(title)},
  description: ${JSON.stringify(description)},

  emailField: ${JSON.stringify(emailField)},
  nameField: ${JSON.stringify(nameField)},

  fields: ${JSON.stringify(fields, null, 2).replace(/\n/g, '\n  ')},
};

/** True once the placeholder entry ids have been replaced with real ones. */
export function schemaIsConfigured() {
  return FORM.fields.every((f) => ${String.raw`/^entry\.\d+$/`}.test(f.entry) && f.entry !== 'entry.000000000');
}

/** Server-side validation. Returns an array of human-readable errors. */
export function validate(body) {
  const errors = [];
  for (const f of FORM.fields) {
    const raw = body[f.name];
    const value = typeof raw === 'string' ? raw.trim() : '';

    if (f.required && value === '') { errors.push(\`\${f.label} is required.\`); continue; }
    if (value === '') continue;

    if (f.maxLength && value.length > f.maxLength) errors.push(\`\${f.label} is too long.\`);
    if (f.type === 'email' && !${String.raw`/^[^\s@]+@[^\s@]+\.[^\s@]+$/`}.test(value)) {
      errors.push(\`\${f.label} does not look like a valid email address.\`);
    }
    if (f.pattern && !new RegExp(f.pattern).test(value)) {
      errors.push(f.patternMessage || \`\${f.label} is not in the expected format.\`);
    }
    if (f.type === 'choice' && f.options?.length && !f.options.includes(value)) {
      errors.push(\`\${f.label} must be one of: \${f.options.join(', ')}.\`);
    }
  }
  return errors;
}
`;
}

async function main() {
  const arg = process.argv[2] || FORM.responseUrl;
  const viewUrl = arg.replace(/\/formResponse.*$/, '/viewform');
  const responseUrl = viewUrl.replace(/\/viewform.*$/, '/formResponse');

  console.log(`Fetching: ${viewUrl}\n`);

  let html;
  try {
    html = await (await fetch(viewUrl, {
      headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/124.0 Safari/537.36' },
    })).text();
  } catch (err) {
    console.error(`Could not reach the form: ${err.message}`);
    return 1;
  }

  if (!html.includes('FB_PUBLIC_LOAD_DATA_')) {
    console.error('Could not read the form anonymously — it still requires sign-in.\n');
    console.error('Fix: open the form -> Settings -> Responses -> turn OFF');
    console.error('     "Restrict to users in <your org>", then re-run this.\n');
    console.error('Manual fallback: open the form while signed in, press F12, and paste');
    console.error('this into the Console to copy the field list to your clipboard:\n');
    console.error(CONSOLE_SNIPPET + '\n');
    return 2;
  }

  const m = html.match(/FB_PUBLIC_LOAD_DATA_\s*=\s*(\[[\s\S]*?\]);\s*<\/script>/);
  if (!m) { console.error('Found the payload but could not extract it.'); return 3; }

  const data = JSON.parse(m[1]);
  const title = data[3] || data[1]?.[8] || 'Registration Form';
  const description = data[1]?.[0] || '';
  const items = data[1]?.[1] || [];

  const fields = [];
  for (const item of items) {
    const label = item[1] || '';
    const code = item[3];
    if (!Array.isArray(item[4])) continue; // section break / image
    for (const entry of item[4]) {
      const id = entry?.[0];
      if (id == null) continue;
      const options = Array.isArray(entry[1])
        ? entry[1].map((o) => o?.[0]).filter((o) => o != null && o !== '')
        : [];
      const f = {
        name: slug(label, id),
        entry: `entry.${id}`,
        label,
        type: /e-?mail/i.test(label) ? 'email' : (TYPE[code] || 'short'),
        required: !!entry[2],
      };
      if (options.length) f.options = options;
      fields.push(f);
    }
  }

  if (!fields.length) { console.error('No answerable questions found.'); return 4; }

  const emailField = (fields.find((f) => f.type === 'email') || fields.find((f) => /mail/i.test(f.label)) || {}).name || '';
  const nameField = (fields.find((f) => /name/i.test(f.label)) || {}).name || '';

  console.log(`Title : ${title}`);
  console.log(`Fields: ${fields.length}\n`);
  for (const f of fields) {
    console.log(`  ${f.entry.padEnd(20)} ${(f.required ? 'req' : '   ')}  ${f.type.padEnd(9)} ${f.label}`);
    if (f.options) f.options.forEach((o) => console.log(`${' '.repeat(38)}- ${o}`));
  }
  if (!emailField) console.warn('\n!! No email question detected — set FORM.emailField by hand.');

  writeFileSync(
    new URL('../lib/form-schema.js', import.meta.url),
    buildSchemaFile({ responseUrl, title, description, emailField, nameField, fields })
  );
  console.log('\nWrote lib/form-schema.js — the web form now mirrors the Google Form.');
  return 0;
}

process.exitCode = await main();
